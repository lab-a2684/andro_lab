#!/usr/bin/env bash
# Regenerate the canonical additive lab patch from the pinned snapshots.
#
# The vulnerable tarball supplies pristine copies of the two edited existing
# files; kgsl_testgpu.c is new.  Keeping this generator in the lab prevents the
# reviewable patch from drifting away from the trees that actually build.
set -Eeuo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CVE_DIR="$(cd "$HERE/.." && pwd)"
ARCHIVE="$CVE_DIR/.work/archives/msm-5.10-36f524a.tar.gz"
SNAP="$CVE_DIR/.work/snapshots/msm-5.10-vulnerable"
OUT="$CVE_DIR/patches/0001-gpu-msm-add-testgpu-software-backend.patch"
OUT2="$CVE_DIR/patches/0002-arm-smmu-allow-lab-memmap.patch"
OUT3="$CVE_DIR/patches/0003-gpu-msm-testgpu-skip-dcvs.patch"

[ -f "$ARCHIVE" ] || { echo "missing pristine archive: $ARCHIVE" >&2; exit 2; }
[ -f "$SNAP/drivers/gpu/msm/kgsl_testgpu.c" ] || {
	echo "missing patched lab source: $SNAP/drivers/gpu/msm/kgsl_testgpu.c" >&2
	exit 2
}

TMP="$(mktemp -d "${TMPDIR:-/tmp}/cve-patch.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/drivers/gpu/msm" "$TMP/drivers/iommu/arm/arm-smmu"
ROOT="$(tar -tzf "$ARCHIVE" | sed -n '1s#/.*##p')"
tar -xOf "$ARCHIVE" "$ROOT/drivers/gpu/msm/Makefile" \
	>"$TMP/drivers/gpu/msm/Makefile"
tar -xOf "$ARCHIVE" "$ROOT/drivers/gpu/msm/adreno-gpulist.h" \
	>"$TMP/drivers/gpu/msm/adreno-gpulist.h"
tar -xOf "$ARCHIVE" "$ROOT/drivers/gpu/msm/kgsl_pwrscale.c" \
	>"$TMP/drivers/gpu/msm/kgsl_pwrscale.c"
tar -xOf "$ARCHIVE" "$ROOT/drivers/iommu/arm/arm-smmu/arm-smmu.c" \
	>"$TMP/drivers/iommu/arm/arm-smmu/arm-smmu.c"
tar -xOf "$ARCHIVE" "$ROOT/drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c" \
	>"$TMP/drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c"

{
	cat <<'HEADER'
From: CVE-2024-23380 lab
Subject: [PATCH] gpu: msm: add a software-only Adreno backend for the CVE lab

The backend supplies only the memory primitive needed by the reproduction:
it walks KGSL's live Qualcomm io-pgtable with the driver's own
arm_lpae_iova_to_phys() path, executes a small PM4 subset, and writes the
normal memstore timestamps.  Protected KGSL files are not changed.

Generated by build/refresh-patches.sh; do not hand-edit.
HEADER

	diff -u --label /dev/null \
		--label b/drivers/gpu/msm/kgsl_testgpu.c \
		/dev/null "$SNAP/drivers/gpu/msm/kgsl_testgpu.c" || :
	diff -u --label a/drivers/gpu/msm/Makefile \
		--label b/drivers/gpu/msm/Makefile \
		"$TMP/drivers/gpu/msm/Makefile" \
		"$SNAP/drivers/gpu/msm/Makefile" || :
	diff -u --label a/drivers/gpu/msm/adreno-gpulist.h \
		--label b/drivers/gpu/msm/adreno-gpulist.h \
		"$TMP/drivers/gpu/msm/adreno-gpulist.h" \
		"$SNAP/drivers/gpu/msm/adreno-gpulist.h" || :
} >"$OUT"

{
	cat <<'HEADER'
From: CVE-2024-23380 lab
Subject: [PATCH] iommu: arm-smmu: allow the lab RAM-backed synthetic SMMU

The stock QEMU virt machine has no SMMU device.  The lab therefore backs the
synthetic qcom,qsmmu-v500 register file with no-map RAM.  Real targets never
set qcom,testgpu-memmap and keep the upstream ioremap path.

Generated by build/refresh-patches.sh; do not hand-edit.
HEADER

	diff -u --label a/drivers/iommu/arm/arm-smmu/arm-smmu.c \
		--label b/drivers/iommu/arm/arm-smmu/arm-smmu.c \
		"$TMP/drivers/iommu/arm/arm-smmu/arm-smmu.c" \
		"$SNAP/drivers/iommu/arm/arm-smmu/arm-smmu.c" || :
	diff -u --label a/drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c \
		--label b/drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c \
		"$TMP/drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c" \
		"$SNAP/drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c" || :
} >"$OUT2"

{
	cat <<'HEADER'
From: CVE-2024-23380 lab
Subject: [PATCH] gpu: msm: skip DCVS power scaling for testgpu

The QEMU lab has no secure world or SCM DCVS service.  Skip the optional
devfreq governor for the synthetic GPU; the fixed clock and generic KGSL
power state machine remain active.

Generated by build/refresh-patches.sh; do not hand-edit.
HEADER

	diff -u --label a/drivers/gpu/msm/kgsl_pwrscale.c \
		--label b/drivers/gpu/msm/kgsl_pwrscale.c \
		"$TMP/drivers/gpu/msm/kgsl_pwrscale.c" \
		"$SNAP/drivers/gpu/msm/kgsl_pwrscale.c" || :
} >"$OUT3"

echo "wrote $OUT ($(wc -l <"$OUT") lines)"
sha256sum "$OUT"
echo "wrote $OUT2 ($(wc -l <"$OUT2") lines)"
sha256sum "$OUT2"
echo "wrote $OUT3 ($(wc -l <"$OUT3") lines)"
sha256sum "$OUT3"
